// A delegated specialist cannot open the native selector: the runner strips
// `ask_user_question` from every child because a child has no UI. The templates
// answered that by asking the child to return options "in the Return Contract", a
// contract with no field for them, so a real design fork left the child as a numbered
// prose list and the Producer relayed it verbatim.
//
// Gentle Shell solves it one level down (`docs/gentle-shell.md:292`): the child calls
// `subagent_parent_message`, a `kind: "query"` frame WAITS for one strictly correlated
// reply, and the child keeps running. This module is that channel for the studio.
//
// Three deliberate differences, each for a stated reason:
//   1. Transport is a Unix socket named by an env var, not the RDD session transport.
//      The child already speaks Pi RPC over stdio (`--mode rpc`), and putting decision
//      frames on that stream would corrupt it; a side socket cannot.
//   2. The wait budget is minutes, not Gentle Shell's 30 seconds, because the other
//      end of the query is a human choosing a game genre.
//   3. Nothing here imports Pi: the protocol is testable with real sockets alone.

import { createServer, connect, type Server, type Socket } from "node:net";
import { chmodSync, existsSync, mkdtempSync, mkdirSync, rmSync, statSync, unlinkSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

/** Wire version. A frame that does not declare it is not a frame we understand. */
export const CHANNEL_VERSION = 1;

/** Hard ceiling for one line of the stream, so a hostile or broken peer cannot buffer us to death. */
export const MAX_FRAME_BYTES = 64 * 1024;

/** Gentle Shell's bound, kept: a child with five open decisions is not asking, it is stalling. */
export const MAX_PENDING_QUERIES = 4;

/** One query or reply payload. A decision and its options fit well inside this. */
export const MAX_MESSAGE_BYTES = 8 * 1024;

/**
 * How long a child waits for the human. Deliberately generous: the answer is a person
 * reading options and picking one, not another agent replying in a second. Override
 * with PI_STUDIO_QUERY_TIMEOUT_MS when a test needs a shorter clock.
 */
export const DEFAULT_QUERY_TIMEOUT_MS = 15 * 60_000;

/** Socket paths are length-capped by the OS; UNIX_PATH_MAX is 104 on macOS, 108 on Linux. */
const MAX_SOCKET_PATH_BYTES = 100;

export interface ChannelChoice {
	label: string;
	description?: string;
}

export interface ChannelQuery {
	/** Parent-visible correlation id. Generated by the child, never by the human. */
	id: string;
	message: string;
	choices: ChannelChoice[];
}

export interface ParentChannelOptions {
	/** Socket path to listen on. Use channelSocketPath() to derive one safely. */
	socketPath: string;
	/** Called once per well-formed query. Answer with reply(). */
	onQuery: (query: ChannelQuery) => void;
	/** A child endpoint disconnected. Its unanswered queries are gone with it. */
	onDisconnect?: () => void;
}

export interface ChildChannelOptions {
	/** Wait budget per query. Defaults to DEFAULT_QUERY_TIMEOUT_MS. */
	timeoutMs?: number;
}

interface PendingQuery {
	resolve: (answer: string) => void;
	reject: (error: Error) => void;
	timer: ReturnType<typeof setTimeout>;
}

/**
 * Derive a socket path that fits the OS limit and lives in a directory only this user
 * can enter. With no root, a private temp directory is created and owned by the caller
 * (ParentChannel.close removes only the socket, so the directory is the caller's).
 */
export function channelSocketPath(id: string, rootDirectory?: string): string {
	// Short on purpose: macOS puts TMPDIR under /var/folders/... and the socket
	// path budget is 100 bytes, so this name is part of a real constraint.
	const safeId = String(id).replace(/[^A-Za-z0-9_-]/g, "").slice(0, 12) || "channel";

	// Windows has no unix sockets: the equivalent is a named pipe, which lives in a
	// namespace rather than the filesystem and needs no path budget.
	if (process.platform === "win32") {
		return `\\\\.\\pipe\\pi-studio-${safeId}`;
	}

	const root = rootDirectory ?? mkdtempSync(join(tmpdir(), "pi-std-"));
	if (!rootDirectory) {
		try {
			chmodSync(root, 0o700);
		} catch {
			// A temp directory we cannot tighten is still usable; the socket mode below
			// is the real boundary.
		}
	} else if (!existsSync(root)) {
		mkdirSync(root, { recursive: true, mode: 0o700 });
	}

	const candidate = join(root, `${safeId}.sock`);
	if (Buffer.byteLength(candidate) > MAX_SOCKET_PATH_BYTES) {
		throw new Error(
			`channel path too long for a unix socket: ${Buffer.byteLength(candidate)} bytes (max ${MAX_SOCKET_PATH_BYTES})`,
		);
	}
	return candidate;
}

/** One newline-delimited JSON frame. Anything else on the wire is a protocol violation. */
function writeFrame(socket: Socket, frame: Record<string, unknown>): boolean {
	if (socket.destroyed || !socket.writable) return false;
	socket.write(`${JSON.stringify({ v: CHANNEL_VERSION, ...frame })}\n`);
	return true;
}

/**
 * Split a socket's data into bounded lines. Returns frames to handle and whether the
 * peer violated the framing contract (an oversized line, an unparsable one).
 */
function createLineReader(onFrame: (frame: any) => void, onViolation: (reason: string) => void) {
	let buffer = "";
	return (chunk: string) => {
		buffer += chunk;
		const lines = buffer.split("\n");
		buffer = lines.pop() ?? "";
		if (Buffer.byteLength(buffer) > MAX_FRAME_BYTES) {
			onViolation("frame too large");
			return;
		}
		for (const rawLine of lines) {
			const line = rawLine.trim();
			if (!line) continue;
			let frame: any;
			try {
				frame = JSON.parse(line);
			} catch {
				// A malformed line is dropped, not fatal: the peer may have written a
				// diagnostic, and killing the channel would lose a live decision.
				continue;
			}
			if (!frame || frame.v !== CHANNEL_VERSION) continue;
			onFrame(frame);
		}
	};
}

/**
 * Parent end of the channel. Owns the socket, surfaces every well-formed query, and
 * refuses a reply for anything that is not currently pending — which is what makes
 * "one reply settles one query" true rather than aspirational.
 */
export class ParentChannel {
	readonly socketPath: string;
	private readonly server: Server;
	private readonly onQuery: (query: ChannelQuery) => void;
	private readonly onDisconnect?: () => void;
	/** query id -> the child socket that asked. The id alone is not enough: two children
	 * could collide, and a reply must never reach the wrong process. */
	private readonly queries = new Map<string, Socket>();
	private readonly sockets = new Set<Socket>();
	private closed = false;

	private constructor(options: ParentChannelOptions, server: Server) {
		this.socketPath = options.socketPath;
		this.server = server;
		this.onQuery = options.onQuery;
		this.onDisconnect = options.onDisconnect;
	}

	static async create(options: ParentChannelOptions): Promise<ParentChannel> {
		const isPipe = process.platform === "win32";
		if (!isPipe) {
			// A socket file left by a crashed parent would make listen fail; removing it
			// is safe because the path is ours by construction.
			try {
				if (existsSync(options.socketPath)) unlinkSync(options.socketPath);
			} catch {
				// Raced with the previous owner; listen will report it if it still matters.
			}
		}

		let channel: ParentChannel | undefined;
		const server = createServer((socket) => channel?.attach(socket));
		channel = new ParentChannel(options, server);

		await new Promise<void>((resolve, reject) => {
			const onError = (error: Error) => {
				server.off("listening", onListening);
				reject(error);
			};
			const onListening = () => {
				server.off("error", onError);
				resolve();
			};
			server.once("error", onError);
			server.once("listening", onListening);
			server.listen(options.socketPath);
		});

		if (!isPipe) {
			try {
				// The directory is 0700, but the socket inside it is what a peer connects
				// to, so its own mode is the boundary that matters.
				chmodSync(options.socketPath, 0o600);
			} catch {
				// Best effort: a platform that ignores socket modes already denied access.
			}
		}
		return channel;
	}

	private attach(socket: Socket): void {
		if (this.closed) {
			socket.destroy();
			return;
		}
		this.sockets.add(socket);
		socket.setEncoding("utf8");

		const read = createLineReader(
			(frame) => {
				// A child that gave up (timeout, or its own shutdown) says so, so a late answer
				// is refused instead of vanishing into a socket nobody is reading.
				if (frame.kind === "cancel") {
					if (typeof frame.id === "string" && frame.id) this.queries.delete(frame.id);
					return;
				}
				if (frame.kind !== "query") return;
				if (typeof frame.id !== "string" || !frame.id) return;
				if (typeof frame.message !== "string" || !frame.message) return;
				if (this.queries.has(frame.id)) return; // a reused id would shadow a live decision
				const choices: ChannelChoice[] = Array.isArray(frame.choices)
					? frame.choices
						.filter((c: any) => c && typeof c.label === "string" && c.label)
						.map((c: any) => ({
							label: String(c.label),
							...(typeof c.description === "string" && c.description ? { description: c.description } : {}),
						}))
					: [];
				this.queries.set(frame.id, socket);
				this.onQuery({ id: frame.id, message: frame.message, choices });
			},
			() => socket.destroy(),
		);

		socket.on("data", read);
		socket.on("error", () => {});
		socket.on("close", () => {
			this.sockets.delete(socket);
			for (const [id, owner] of this.queries) {
				if (owner === socket) this.queries.delete(id);
			}
			this.onDisconnect?.();
		});
	}

	/** Ids still waiting for an answer. A decision that is not here cannot be replied to. */
	pending(): string[] {
		return [...this.queries.keys()];
	}

	/**
	 * Answer exactly one pending query. Returns false for an unknown id — including a
	 * second reply to an already settled one — so a duplicate can never override the
	 * answer the child already received.
	 */
	reply(queryId: string, message: string): boolean {
		if (this.closed) return false;
		const socket = this.queries.get(queryId);
		if (!socket) return false;
		if (socket.destroyed) {
			this.queries.delete(queryId);
			return false;
		}
		if (Buffer.byteLength(message) > MAX_MESSAGE_BYTES) return false;
		this.queries.delete(queryId);
		return writeFrame(socket, { id: queryId, kind: "reply", message });
	}

	/**
	 * Synchronous on purpose. A fire-and-forget close races the caller: the sockets are
	 * already gone, so waiting for the server callback buys nothing and lets a process
	 * that is about to exit leave the socket file and its directory behind.
	 */
	close(): void {
		if (this.closed) return;
		this.closed = true;
		this.queries.clear();
		for (const socket of this.sockets) socket.destroy();
		this.sockets.clear();
		this.server.close();
		// Destroyed sockets do not always finish their close handshake before the
		// event loop drains; dropping the remaining connections keeps the port free.
		(this.server as any).closeAllConnections?.();
		if (process.platform !== "win32") {
			try {
				if (statSync(this.socketPath).isSocket()) unlinkSync(this.socketPath);
			} catch {
				// Already gone: close() is idempotent by contract.
			}
		}
	}
}

/**
 * Child end of the channel. One connection, at most MAX_PENDING_QUERIES open decisions,
 * one reply per query, and every exit path (reply, timeout, parent close, our own close)
 * settles exactly once.
 */
export class ChildChannel {
	private readonly socket: Socket;
	private readonly timeoutMs: number;
	private readonly pending = new Map<string, PendingQuery>();
	private sequence = 0;
	private closed = false;

	private constructor(socket: Socket, timeoutMs: number) {
		this.socket = socket;
		this.timeoutMs = timeoutMs;
	}

	static async connect(socketPath: string, options: ChildChannelOptions = {}): Promise<ChildChannel> {
		const socket = connect(socketPath);
		await new Promise<void>((resolve, reject) => {
			const onError = (error: Error) => {
				socket.off("connect", onConnect);
				reject(error);
			};
			const onConnect = () => {
				socket.off("error", onError);
				resolve();
			};
			socket.once("error", onError);
			socket.once("connect", onConnect);
		});

		const envTimeout = Number(process.env.PI_STUDIO_QUERY_TIMEOUT_MS);
		const timeoutMs = options.timeoutMs
			?? (Number.isFinite(envTimeout) && envTimeout > 0 ? envTimeout : DEFAULT_QUERY_TIMEOUT_MS);
		const channel = new ChildChannel(socket, timeoutMs);
		channel.listen();
		return channel;
	}

	private listen(): void {
		this.socket.setEncoding("utf8");
		const read = createLineReader(
			(frame) => {
				if (frame.kind !== "reply") return;
				// Strict correlation: an id we did not open settles nothing, and a reply
				// without a message is not an answer.
				if (typeof frame.id !== "string" || !frame.id) return;
				if (typeof frame.message !== "string") return;
				const entry = this.pending.get(frame.id);
				if (!entry) return;
				this.pending.delete(frame.id);
				clearTimeout(entry.timer);
				entry.resolve(frame.message);
			},
			() => this.socket.destroy(),
		);
		this.socket.on("data", read);
		this.socket.on("error", () => {});
		this.socket.on("close", () => this.settleAll("channel closed before the parent answered", this.closed));
	}

	/**
	 * Ask the parent and wait. Rejects before touching the wire when the message is
	 * oversized or four decisions are already open: a queued decision nobody reads is
	 * worse than a refusal the child can report.
	 */
	ask(message: string, choices: ChannelChoice[] = []): Promise<string> {
		if (this.closed) return Promise.reject(new Error("channel_busy: channel is closed"));
		if (Buffer.byteLength(message) > MAX_MESSAGE_BYTES) {
			return Promise.reject(new Error(`channel_busy: message too large (max ${MAX_MESSAGE_BYTES} bytes)`));
		}
		if (this.pending.size >= MAX_PENDING_QUERIES) {
			return Promise.reject(
				new Error(`channel_busy: ${MAX_PENDING_QUERIES} decisions already pending for this agent`),
			);
		}

		this.sequence += 1;
		const id = `q${this.sequence}`;
		return new Promise<string>((resolve, reject) => {
			const timer = setTimeout(() => {
				if (!this.pending.has(id)) return;
				this.pending.delete(id);
				// Tell the parent this decision is off the table: otherwise it keeps the id
				// pending and accepts an answer nobody will ever read.
				writeFrame(this.socket, { id, kind: "cancel" });
				reject(new Error(`query ${id} timed out after ${this.timeoutMs}ms without an answer`));
			}, this.timeoutMs);
			// A timer must not hold the process open: a specialist that died waiting is
			// already gone.
			(timer as any).unref?.();
			this.pending.set(id, { resolve, reject, timer });

			const sent = writeFrame(this.socket, {
				id,
				kind: "query",
				message,
				choices: choices.map((c) => ({
					label: String(c.label),
					...(c.description ? { description: String(c.description) } : {}),
				})),
			});
			if (!sent) {
				this.pending.delete(id);
				clearTimeout(timer);
				reject(new Error("channel closed before the query could be sent"));
			}
		});
	}

	close(): void {
		this.closed = true;
		this.settleAll("channel closed before the parent answered", true);
		if (!this.socket.destroyed) this.socket.destroy();
	}

	private settleAll(reason: string, _intentional: boolean): void {
		for (const [id, entry] of this.pending) {
			this.pending.delete(id);
			clearTimeout(entry.timer);
			writeFrame(this.socket, { id, kind: "cancel" });
			entry.reject(new Error(`${reason} (${id})`));
		}
	}
}

/** Remove a private channel directory and anything left inside it. */
export function removeChannelDirectory(directory: string): void {
	try {
		rmSync(directory, { recursive: true, force: true });
	} catch {
		// Nothing to reclaim.
	}
}
